// Deterministic structural edits — insert / move / remove / wrap / unwrap an
// element in source. Built on an offset-precise element tree (htmlScan), so
// formatting is irrelevant: one element per line, many per line, minified, or
// hand-written inline all resolve and splice identically. This is the
// direct-manipulation path (drag in the canvas or Layers, the Add panel); it
// must NOT defer to the agent for anything a person can point at.
//
// An element is pinned STRUCTURALLY: from its DOM ancestor path we find the
// deepest ancestor that is unique in source AND has no same-tag siblings (the
// anchor), then descend into it by same-tag child index. A count guard at each
// step (source child count === DOM count) means the only thing that can't
// resolve is genuinely non-deterministic — content generated by a `{…map…}`
// expression, where one source element stands for many rendered ones. Static
// and literal markup (what marketing sites are) always resolves.

import fs from 'fs';
import path from 'path';
import * as editEngine from './editEngine';
import { parseNodes } from './htmlScan';
import type { ElementContext, ElementPathLevel, InsertPosition, InsertSpec, MoveSpec, SubjectSpec, StructuralEditResult } from '../shared/radialApi';
import type { WrittenFileEdit } from './editEngine';
import type { HtmlNode, ParsedHtml } from './htmlScan';

/** One source file, read and parsed (the snapshot, cached by mtime and size). */
export interface SourceEntry {
  mtimeMs: number;
  size: number;
  /** Relative to the repo. */
  relFile: string;
  src: string;
  tree: ParsedHtml;
}

/** An element resolved to its exact source node. */
export interface ResolvedTarget {
  entry: SourceEntry;
  node: HtmlNode;
  fail?: undefined;
}
/** Why an element couldn't be pinned to one source node (returned as-is as the edit's failure). */
export interface ResolveFailure {
  fail: StructuralEditFailure & { reason: 'bad-args' | 'unclosed' | 'count-mismatch' | 'no-anchor' };
  entry?: undefined;
  node?: undefined;
}
/** resolveTarget: the element's source node, or why it couldn't be pinned. */
export type NodeResolution = ResolvedTarget | ResolveFailure;

/** A structural edit written: the window's StructuralEditResult success plus the two contents for undo. */
export type StructuralEditDone = Extract<StructuralEditResult, { ok: true }> & WrittenFileEdit;
export type StructuralEditFailure = Extract<StructuralEditResult, { ok: false }>;
export type StructuralEditOutcome = StructuralEditDone | StructuralEditFailure;

// A path level as the matchers read it: a captured ElementPathLevel, or one
// pathOf builds from a legacy selection (whose tag and id may be missing).
// `tagName` and `classList` are the selection spellings the matchers also accept.
// Neither producer (the overlay's buildStructuralPath, pathOf's legacy levels)
// sets them, so the matchers' `|| level.tagName` and `|| level.classList`
// fallbacks never fire today.
interface PathLevel extends Omit<ElementPathLevel, 'tag' | 'id'> {
  tag?: string | null;
  id?: string | null;
  tagName?: string | null;
  classList?: string[];
}

// A source node and the file it sits in.
interface Hit {
  entry: SourceEntry;
  node: HtmlNode;
}

const MAX_RANGE = 40000; // chars — an element bigger than this is a page, not a target
const JSX_EXTS = new Set(['.js', '.jsx', '.ts', '.tsx', '.mjs', '.cjs']);
const esc = (s: string) => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// ── needles + path ───────────────────────────────────────────────────────
// Attribute signatures an element still has when it carries no text/class/id.
function needlesFrom(sel: PathLevel): string[] {
  const out: string[] = [];
  const src = String(sel.src || '');
  if (src.startsWith('data:')) out.push(src.slice(0, 60));
  else if (src) out.push(src.split(/[?#]/)[0].split('/').pop()!);
  if (sel.alt) out.push(String(sel.alt).slice(0, 80));
  if (sel.href && String(sel.href).length > 1) out.push(String(sel.href).slice(0, 120));
  if (sel.ariaLabel) out.push(String(sel.ariaLabel).slice(0, 80));
  if (sel.placeholder) out.push(String(sel.placeholder).slice(0, 80));
  return out.filter((v) => v && v.length >= 4);
}
// A normalized ancestor path (element at index 0, up toward <body>), from the
// rich `path` captured in the page or the legacy parent/nthOfTag single level.
function pathOf(sel: ElementContext): PathLevel[] {
  if (Array.isArray(sel.path) && sel.path.length) return sel.path;
  const el: PathLevel = { tag: sel.tagName, id: sel.id, cls: sel.classList || [], own: (sel.text || '').trim().slice(0, 60),
    src: sel.src, href: sel.href, alt: sel.alt, ariaLabel: sel.ariaLabel, placeholder: sel.placeholder,
    nth: sel.nthOfTag || 0, cnt: sel.tagSiblings || 1 };
  if (sel.parent) return [el, { tag: sel.parent.tagName, id: sel.parent.id, cls: sel.parent.classList || [], nth: 0, cnt: 1 }];
  return [el];
}

// ── parsed-source snapshot, cached by (mtime,size) ─────────────────────────
// Each file is read AND parsed once; a rapid burst re-reads only the file it
// just wrote (our own writes bump mtime, dropping the stale entry).
const _cache = new Map<string, SourceEntry>(); // absPath -> { mtimeMs, size, relFile, src, tree }
function snapshot(repoDir: string): SourceEntry[] {
  const snap: SourceEntry[] = [];
  for (const file of editEngine.listSourceFiles(repoDir)) {
    let st; try { st = fs.statSync(file); } catch { continue; }
    if (st.size > 2 * 1024 * 1024) continue;
    const c = _cache.get(file);
    if (c && c.mtimeMs === st.mtimeMs && c.size === st.size) { snap.push(c); continue; }
    let src; try { src = fs.readFileSync(file, 'utf8'); } catch { continue; }
    const entry = { mtimeMs: st.mtimeMs, size: st.size, relFile: path.relative(repoDir, file), src, tree: parseNodes(src) };
    _cache.set(file, entry); snap.push(entry);
  }
  return snap;
}

// ── node matching ──────────────────────────────────────────────────────────
function allNodes(tree: ParsedHtml): HtmlNode[] { const out: HtmlNode[] = []; const walk = (ns: HtmlNode[]) => ns.forEach((n) => { out.push(n); walk(n.children); }); walk(tree.roots); return out; }
// An element's OWN direct text (excludes descendant elements' text) — a leaf's
// strongest signature; a mapped leaf's text is a `{expr}` so it never matches.
function ownText(node: HtmlNode, src: string): string {
  let t = '', cur = node.openEnd;
  for (const ch of node.children) { t += src.slice(cur, ch.openStart); cur = ch.end; }
  t += src.slice(cur, node.closeStart == null ? node.end : node.closeStart);
  return t.replace(/\s+/g, ' ').trim();
}
function openHasClass(open: string, cls: string): boolean {
  const m = open.match(/(?:class|className)\s*=\s*(["'`])([^"'`]*)\1/);
  return !!m && m[2].split(/\s+/).includes(String(cls));
}
// Does this source node carry the path level's own signature (id / class /
// literal attribute / own-text)? Tag-alone is handled separately (only when the
// level has no same-tag siblings, so it can't be confused).
// How strongly a source node carries a path level's signature. Not a boolean:
// on a Tailwind site every element shares `flex`/`mx-auto`, so "any class
// matches" makes unique elements look ambiguous. A FULL class-set match (the
// DOM's whole classList present) outranks partial overlap; id and own-text
// dominate everything. 0 = no signature.
function signatureStrength(level: PathLevel, node: HtmlNode, src: string): number {
  let s = 0;
  if (level.id && new RegExp(`\\bid\\s*=\\s*["'\`]${esc(level.id)}["'\`]`).test(node.open)) s += 100;
  const cl = (level.cls || level.classList || []).filter((c) => c && String(c).length >= 2);
  let hit = 0; for (const c of cl) if (openHasClass(node.open, c)) hit++;
  if (hit) s += hit + (hit === cl.length ? 20 : 0);
  for (const n of needlesFrom(level)) if (node.open.includes(n)) s += 10;
  if (level.own && level.own.length >= 6 && ownText(node, src).includes(level.own)) s += 50;
  return s;
}
function nodeHasSignature(level: PathLevel, node: HtmlNode, src: string): boolean { return signatureStrength(level, node, src) > 0; }
// Does this candidate sit where the DOM says — the same slot among same-tag
// source siblings, with the same sibling count? true / false, or null when the
// counts disagree (one source node standing for many rendered ones — a
// template — or a root with no siblings to compare).
function positionMatches(node: HtmlNode, level: PathLevel): boolean | null {
  if (!node.parent) return null;
  const tag = node.renderTag || node.tag;
  const kin = node.parent.children.filter((c) => (c.renderTag || c.tag) === tag);
  if (kin.length !== (level.cnt || 1)) return null;
  return kin.indexOf(node) === (level.nth || 0);
}
// How far up the candidate's source ancestry agrees with the DOM path above
// the leaf (tag per level, plus class overlap) — stops at the first divergence
// (a component boundary). Separates twins that live under different parents.
function ancestryScore(node: HtmlNode, path0: PathLevel[], src: string): number {
  let score = 0, n = node;
  for (let i = 1; i < path0.length && n && n.parent; i++) {
    const level = path0[i]; n = n.parent;
    if ((n.renderTag || n.tag) !== String(level.tag || level.tagName || '').toLowerCase()) break;
    // Same strength model as the leaf: an ancestor carrying the level's FULL
    // class set is decisive (the twin under `grid gap-12` vs `grid gap-8`).
    score += 1 + signatureStrength(level, n, src);
    // Positional agreement at this level too: when the ancestor's same-tag
    // sibling count matches the DOM's, its slot must match — the second of two
    // identical grids is told from the first by exactly this.
    if (n.parent) { const t = n.renderTag || n.tag; const kin = n.parent.children.filter((c) => (c.renderTag || c.tag) === t); if (kin.length === (level.cnt || 1)) score += kin.indexOf(n) === (level.nth || 0) ? 2 : -100; }
  }
  return score;
}

// Source elements the DOM never shows: Vue's and Svelte's own (a single-file
// component's <template>, <transition>, <slot>…).
const FRAMEWORK_TAGS = new Set(['template', 'slot', 'component', 'transition', 'transition-group', 'keep-alive', 'teleport', 'suspense']);

// Whether `node` is really inside a capitalized component the scanner reads as
// a void tag (`<Link>` parses as <link>, which can't hold anything), so what
// it wraps is recorded beside it, under the wrong parent.
function insideVoidComponent(node: HtmlNode, src: string): boolean {
  return !!node.parent && node.parent.children.some((s) => {
    if (s.openStart >= node.openStart || !s.isVoid || s.selfClosing || !/^<[A-Z]/.test(s.open)) return false;
    const name = /^<([\w.-]+)/.exec(s.open)![1]; // the test above guarantees a name
    return src.indexOf(`</${name}`, s.openEnd) > node.openStart;
  });
}

// Whether a source node's two nearest parents contradict the DOM path above
// level `from`: a plain element with another tag, or one whose literal classes
// include none of the DOM parent's. A match that's unique in source but sits
// under the wrong parents is another copy of the element (a mobile menu's twin
// of a nav link the page renders from a list), never the one clicked, so it
// mustn't pin an edit. A component in between ends the comparison, since the
// DOM can't see past it: a capitalized one (`<Nav>`, and `<Link>`, which the
// scanner records wrongly), a kebab-case one (Vue's `<base-card>`), or a
// framework element (`<template>`, `svelte:head`). `motion.div` is compared as
// the tag it renders. Ported from Radial Cloud's copy of the engine, which
// stops only at the capitalized ones the scanner nests.
function ancestryContradicts(node: HtmlNode, src: string, path0: PathLevel[], from: number): boolean {
  let n = node;
  for (let i = from + 1; i < Math.min(path0.length, from + 3) && n.parent; i++) {
    if (insideVoidComponent(n, src)) return false;
    n = n.parent;
    if (/^<[A-Z]/.test(n.open) || FRAMEWORK_TAGS.has(n.tag) || /[-:]/.test(n.tag)) return false;
    const level = path0[i];
    if ((n.renderTag || n.tag) !== String(level.tag || level.tagName || '').toLowerCase()) return true;
    const cls = (level.cls || level.classList || []).filter((c) => c && String(c).length >= 2);
    const literal = /(?:class|className)\s*=\s*(["'`])([^"'`]*)\1/.test(n.open);
    if (cls.length && literal && !cls.some((c) => openHasClass(n.open, c))) return true;
  }
  return false;
}

// The deepest path level that pins to exactly ONE source element. Only a
// structurally-unique node (cnt === 1, no same-tag siblings) can be an anchor:
// a node the DOM says is one of many identical siblings can't be told apart in
// source by a signature (a class four mapped items share appears once but
// stands for four), so it's reached only by count-guarded descent from a truly
// unique ancestor (ultimately <body>). Scoped to the current page first.
function anchorFromPath(repoDir: string, path0: PathLevel[], preferFile: string | null | undefined): (Hit & { index: number }) | null {
  const snap = snapshot(repoDir);
  for (let i = 0; i < path0.length; i++) {
    const level = path0[i];
    if ((level.cnt || 1) !== 1) continue;
    const tag = String(level.tag || level.tagName || '').toLowerCase();
    if (!tag) continue;
    const bySig: Hit[] = [], byTag: Hit[] = [];
    for (const entry of snap) {
      for (const node of allNodes(entry.tree)) {
        // NO size cap on anchors: an anchor only needs to be LOCATED (a
        // page-sized <body>/<main> is a perfect anchor — we descend into it to
        // a small element). Capping here excluded every ancestor on a big page
        // and produced "no-anchor" on real, long pages.
        if ((node.renderTag || node.tag) !== tag) continue; // renderTag: motion.div ⇢ div
        byTag.push({ entry, node });
        if (nodeHasSignature(level, node, entry.src)) bySig.push({ entry, node });
      }
    }
    // Keep only the STRONGEST signature matches before testing uniqueness: the
    // one node carrying all of the DOM's classes beats the dozens sharing `flex`.
    const strongest = (list: Hit[]) => { if (list.length < 2) return list; const sc = list.map((x) => signatureStrength(level, x.node, x.entry.src)); const mx = Math.max(...sc); return list.filter((_, k) => sc[k] === mx); };
    for (const list of [strongest(bySig), byTag]) {
      let use = list;
      if (preferFile) { const p = list.filter((x) => x.entry.relFile === preferFile); if (p.length) use = p; }
      if (use.length === 1 && !ancestryContradicts(use[0].node, use[0].entry.src, path0, i)) return { entry: use[0].entry, node: use[0].node, index: i };
    }
  }
  return null;
}

// Well-formed enough to edit (a container we could bound, or a leaf).
function bounded(node: HtmlNode): boolean { return node.selfClosing || node.isVoid || node.closeStart != null; }
// Fallback: find the element straight by its OWN signature within the current
// page file. This covers framework page/layout splits (Astro/Next), where the
// DOM path runs up to a <body> that lives in a SEPARATE layout file — structural
// descent can't cross that component boundary, but the element itself is right
// here in the page, uniquely identified by its class/id/attr/text. Scoped to
// preferFile so a class shared across pages stays unambiguous.
function directLocate(repoDir: string, sel: ElementContext, preferFile: string | null | undefined): Hit | null {
  const el = pathOf(sel)[0];
  if (!el) return null;
  const tag = String(el.tag || el.tagName || '').toLowerCase();
  if (!tag) return null;
  const snap = snapshot(repoDir);
  const find = (entries: SourceEntry[]) => {
    const hits: Hit[] = [];
    for (const entry of entries) {
      for (const node of allNodes(entry.tree)) {
        if ((node.renderTag || node.tag) !== tag || !bounded(node) || !nodeHasSignature(el, node, entry.src)) continue;
        // Guard against MAPPED content: a rendered element carries literal DOM
        // text, a `{item.title}` template does not. If the DOM element has real
        // own-text but this source node doesn't contain it, this is a templated
        // instance — resolving it would edit EVERY rendered copy. Skip it.
        if (el.own && el.own.length >= 6 && !ownText(node, entry.src).includes(el.own)) continue;
        hits.push({ entry, node });
      }
    }
    return hits;
  };
  // Prefer the current page file, but FALL BACK to the whole tree when it yields
  // no unique hit. A framework route file (app/page.tsx) COMPOSES the element's
  // real component (app/components/…) — so the page the app hands us as
  // preferFile legitimately doesn't contain the element. Scoping only to
  // preferFile there returned nothing and broke every homepage edit on
  // app-router sites; the own-text guard keeps the whole-tree search unambiguous.
  // Disambiguate twins the way the DOM already has — by strength, position and
  // ancestry: (1) keep the strongest signature (full class-set match beats
  // sharing `flex`); (2) among equals, the one sitting at the DOM's slot among
  // same-tag source siblings (when the counts agree — static repetition);
  // (3) then the one whose source ancestry best matches the DOM path above.
  // SAFETY: a single source node standing for MANY rendered copies (DOM cnt>1,
  // no own text, sibling counts disagree) is a template — refuse, never edit all.
  const path0 = pathOf(sel);
  const narrow = (hits: Hit[]) => {
    if (hits.length > 1) { const sc = hits.map((h) => signatureStrength(el, h.node, h.entry.src)); const mx = Math.max(...sc); hits = hits.filter((_, k) => sc[k] === mx); }
    if (hits.length > 1) { const pos = hits.filter((h) => positionMatches(h.node, el) === true); if (pos.length) hits = pos; }
    if (hits.length > 1) { const sc = hits.map((h) => ancestryScore(h.node, path0, h.entry.src)); const mx = Math.max(...sc); const best = hits.filter((_, k) => sc[k] === mx); if (best.length === 1) hits = best; }
    if (hits.length !== 1) return null;
    const hit = hits[0];
    if (ancestryContradicts(hit.node, hit.entry.src, path0, 0)) return null; // a hidden twin, not the element clicked
    // Template guard. The DOM says this is one of MANY same-tag siblings and the
    // element has no id/own-text to make it a single instance. If the overlay
    // told us how many siblings share its exact class set (`twins`): >1 and no
    // positional agreement ⇒ one source node rendered N times ⇒ refuse. Without
    // that signal, refuse only when the sibling COUNTS disagree (a component root
    // or a mapped instance) — a slot mismatch alone is just a stale nth on an
    // element the signature already pinned uniquely.
    if ((el.cnt || 1) > 1 && !(el.own && el.own.length >= 6) && !el.id) {
      const pos = positionMatches(hit.node, el);
      const looksTemplate = el.twins != null ? (el.twins > 1 && pos !== true) : (pos === null);
      if (looksTemplate) return null;
    }
    return hit;
  };
  // Decide WITHIN the current page when it has candidates (whole-tree twins
  // elsewhere are never the pointed-at element); only an empty page falls back.
  const inPage = preferFile ? find(snap.filter((e) => e.relFile === preferFile)) : [];
  return inPage.length ? narrow(inPage) : narrow(find(snap)); // one element, pinned — or nothing (ambiguity stays honest)
}
/**
 * Resolve an element to its exact source node (offsets + parsed children).
 * @returns the entry and node, or `fail` with the reason
 */
function resolveTarget(repoDir: string, sel: ElementContext, preferFile?: string | null): NodeResolution {
  if (!sel) return { fail: { ok: false, reason: 'bad-args' } };
  const path0 = pathOf(sel);
  const a = anchorFromPath(repoDir, path0, preferFile);
  const structural = a && ((): (Hit & { unclosed?: undefined }) | { unclosed: true; node?: undefined } | null => {
    let node = a.node;
    for (let j = a.index - 1; j >= 0; j--) {
      const level = path0[j];
      const tag = String(level.tag || level.tagName || '').toLowerCase();
      const kids = node.children.filter((c) => (c.renderTag || c.tag) === tag);
      if (kids.length !== (level.cnt || 0)) return null; // count mismatch — try the direct fallback
      node = kids[level.nth || 0];
      if (!node) return null;
    }
    return bounded(node) ? { entry: a.entry, node } : { unclosed: true };
  })();
  if (structural && structural.node) return structural;
  // Structural descent didn't resolve (framework page/layout split, a mapped
  // ancestor, or an unclosed container) — locate the element directly.
  const direct = directLocate(repoDir, sel, preferFile);
  if (direct) return direct;
  if (structural && structural.unclosed) return { fail: { ok: false, reason: 'unclosed' } };
  return { fail: { ok: false, reason: a ? 'count-mismatch' : 'no-anchor' } };
}

// ── offset + indentation helpers ────────────────────────────────────────────
function lineStart(src: string, off: number): number { return src.lastIndexOf('\n', off - 1) + 1; }
function indentAt(src: string, off: number): string { return (/^[\t ]*/.exec(src.slice(lineStart(src, off))) || [''])[0]; }
// An element's span. When it sits alone on its line(s), the span is those whole
// lines (so a move/remove takes the element AND its line, not a ragged
// fragment); when it shares a line (inline/minified), the span is the element
// itself. `indent` is the element's base line indent.
function elementSpan(src: string, node: HtmlNode): { from: number; to: number; indent: string; alone: boolean } {
  const ls = lineStart(src, node.openStart);
  const before = src.slice(ls, node.openStart);
  let le = src.indexOf('\n', node.end); const hasNl = le >= 0; if (le < 0) le = src.length;
  const after = src.slice(node.end, le);
  if (/^\s*$/.test(before) && /^\s*$/.test(after)) return { from: ls, to: hasNl ? le + 1 : le, indent: before, alone: true };
  return { from: node.openStart, to: node.end, indent: indentAt(src, node.openStart), alone: false };
}
// Re-home a markup block (its first line has no indent, deeper lines carry
// their own relative indent) to `toIndent`, preserving nesting.
function homeMarkup(markup: string, toIndent: string): string {
  return markup.split('\n').map((l) => (l.trim() ? toIndent + l : l)).join('\n');
}
// Re-home an EXISTING element's text (first line already sat at `fromIndent`
// implicitly via its line; deeper lines start with `fromIndent`).
function homeElement(elText: string, fromIndent: string, toIndent: string): string {
  return elText.split('\n').map((l, i) => {
    if (i === 0) return toIndent + l;
    if (!l.trim()) return l;
    return l.startsWith(fromIndent) ? toIndent + l.slice(fromIndent.length) : l;
  }).join('\n');
}
function fitMarkupToFile(markup: string, relFile: string): string {
  return JSX_EXTS.has(path.extname(relFile).toLowerCase()) ? markup.replace(/\bclass="/g, 'className="') : markup;
}
function write(repoDir: string, entry: SourceEntry, next: string, atOffset: number): StructuralEditDone {
  fs.writeFileSync(path.join(repoDir, entry.relFile), next, 'utf8');
  return { ok: true, file: path.join(repoDir, entry.relFile), relFile: entry.relFile,
    prevContent: entry.src, newContent: next, line: 1 + (next.slice(0, atOffset || 0).match(/\n/g) || []).length };
}
// Remove [rmFrom,rmTo) and insert `text` at original-coordinate offset `at`
// (rmFrom===rmTo for a pure insert). `at` is always outside the removed range.
function splice(src: string, rmFrom: number, rmTo: number, at: number, text: string): string {
  if (at <= rmFrom) return src.slice(0, at) + text + src.slice(at, rmFrom) + src.slice(rmTo);
  return src.slice(0, rmFrom) + src.slice(rmTo, at) + text + src.slice(at);
}
// The landing point + inserted text for placing `block` (indented to the
// target's context, newline-framed) before/after/inside a target node. `block`
// is produced by the caller via homeMarkup/homeElement to the returned indent.
function landingFor(src: string, t: HtmlNode, position: InsertPosition, makeBlock: (indent: string) => string): { at: number; text: string } {
  if (position === 'inside') {
    const indent = indentAt(src, t.openStart);
    const child = makeBlock(indent + '  ');
    const closeLS = lineStart(src, t.closeStart!);
    if (/^\s*$/.test(src.slice(closeLS, t.closeStart!))) return { at: closeLS, text: child + '\n' }; // close on its own line
    return { at: t.closeStart!, text: '\n' + child + '\n' + indent }; // one-liner: open it up
  }
  const span = elementSpan(src, t);
  const block = makeBlock(span.indent);
  if (span.alone) return { at: position === 'before' ? span.from : span.to, text: block + '\n' };
  // Inline target (shares its line): drop the block on a fresh adjacent line.
  return position === 'before'
    ? { at: span.from, text: block + '\n' + span.indent }
    : { at: span.to, text: '\n' + block };
}

// ── operations ───────────────────────────────────────────────────────────────
/** Insert `markup` before / after target, or inside it as last child. */
function applyInsert(repoDir: string, { anchor, position, markup, preferFile }: InsertSpec): StructuralEditOutcome {
  if (!repoDir || !anchor || !markup) return { ok: false, reason: 'bad-args' };
  const r = resolveTarget(repoDir, anchor, preferFile);
  if (r.fail) return r.fail;
  const { entry, node } = r;
  if (position === 'inside' && (node.selfClosing || node.isVoid)) return { ok: false, reason: 'void-parent' };
  const fitted = fitMarkupToFile(markup, entry.relFile);
  const { at, text } = landingFor(entry.src, node, position, (indent) => homeMarkup(fitted, indent));
  return write(repoDir, entry, splice(entry.src, at, at, at, text), at);
}

/** Move `subject` before/after `target`, or inside it as last child. */
function applyMove(repoDir: string, { subject, target, position, preferFile }: MoveSpec): StructuralEditOutcome {
  if (!repoDir || !subject || !target) return { ok: false, reason: 'bad-args' };
  const ra = resolveTarget(repoDir, subject, preferFile); if (ra.fail) return ra.fail;
  const rb = resolveTarget(repoDir, target, preferFile); if (rb.fail) return rb.fail;
  if (ra.entry.relFile !== rb.entry.relFile) return { ok: false, reason: 'cross-file' };
  const src = ra.entry.src, s = ra.node, t = rb.node;
  if (t.openStart >= s.openStart && t.end <= s.end) return { ok: false, reason: 'nested' }; // target inside subject
  if (position === 'inside' && (t.selfClosing || t.isVoid)) return { ok: false, reason: 'void-parent' };
  const sSpan = elementSpan(src, s);
  const elText = src.slice(s.openStart, s.end);
  const { at, text } = landingFor(src, t, position, (indent) => homeElement(elText, sSpan.indent, indent));
  return write(repoDir, ra.entry, splice(src, sSpan.from, sSpan.to, at, text), Math.min(sSpan.from, at));
}

/** Remove `subject` (and the line it owned). */
function applyRemove(repoDir: string, { subject, preferFile }: SubjectSpec): StructuralEditOutcome {
  if (!repoDir || !subject) return { ok: false, reason: 'bad-args' };
  const r = resolveTarget(repoDir, subject, preferFile);
  if (r.fail) return r.fail;
  const span = elementSpan(r.entry.src, r.node);
  return write(repoDir, r.entry, r.entry.src.slice(0, span.from) + r.entry.src.slice(span.to), span.from);
}

/** Wrap `subject` in a fresh uniquely-classed <div>. */
function applyWrap(repoDir: string, { subject, preferFile }: SubjectSpec): StructuralEditOutcome {
  if (!repoDir || !subject) return { ok: false, reason: 'bad-args' };
  const r = resolveTarget(repoDir, subject, preferFile);
  if (r.fail) return r.fail;
  const { entry, node } = r;
  const src = entry.src;
  const cls = 'block-' + Math.random().toString(36).slice(2, 7);
  const attr = JSX_EXTS.has(path.extname(entry.relFile).toLowerCase()) ? 'className' : 'class';
  const span = elementSpan(src, node);
  const inner = homeElement(src.slice(node.openStart, node.end), span.indent, span.indent + '  ');
  const next = src.slice(0, span.from)
    + `${span.indent}<div ${attr}="${cls}">\n${inner}\n${span.indent}</div>\n`
    + src.slice(span.to);
  return { ...write(repoDir, entry, next, span.from), wrapperClass: cls };
}

/** Unwrap `subject` — drop its own tags, keep its children one indent out. */
function applyUnwrap(repoDir: string, { subject, preferFile }: SubjectSpec): StructuralEditOutcome {
  if (!repoDir || !subject) return { ok: false, reason: 'bad-args' };
  const r = resolveTarget(repoDir, subject, preferFile);
  if (r.fail) return r.fail;
  const { entry, node } = r;
  if (node.selfClosing || node.isVoid || node.closeStart == null || !node.children.length) return { ok: false, reason: 'no-children' };
  const src = entry.src;
  const span = elementSpan(src, node);
  // Trim the wrapper's own boundary whitespace: a leading newline and the
  // trailing newline+indent that sat before its close tag (else that indent is
  // orphaned onto a blank line).
  const inner = src.slice(node.openEnd, node.closeStart).replace(/^\n/, '').replace(/\n[ \t]*$/, '');
  const deeper = span.indent + '  ';
  const dedented = inner.split('\n').map((l) => (l.startsWith(deeper) ? span.indent + l.slice(deeper.length) : l)).join('\n');
  return write(repoDir, entry, src.slice(0, span.from) + dedented + '\n' + src.slice(span.to), span.from);
}

export { applyInsert, applyMove, applyRemove, applyWrap, applyUnwrap, resolveTarget, parseNodes };
