/**
 * The `radial` shim written into userData/shims — the directory the PTY daemon
 * prepends to every Radial terminal's PATH (term-daemon.js). It guarantees the
 * CLI is reachable inside the app's own agent terminals even when the symlink
 * the app installs on first launch (cliInstall.js) landed somewhere off that
 * PATH, and it always points at the RUNNING app's bundle, so a terminal can
 * never call a stale copy. It also names the app's control socket so the
 * client skips flavor discovery. Pure string builder, unit-tested.
 */

const dq = (s: string): string => String(s).replace(/[\\"$`]/g, (c) => '\\' + c); // safe inside sh double quotes

/** What the shim needs: the running app's `radial` script, and its control socket. */
export interface ShimSourceOptions {
  /** Absolute path of the bundled `radial` script the shim execs. Required (throws without it). */
  bin: string;
  /** The app's control socket, exported as RADIAL_CLI_SOCK unless the caller already set one. */
  sock?: string;
  /**
   * Which Radial the shim's terminals belong to, exported as RADIAL_CLI_FLAVOR:
   * `radial serve` writes headless, so bin/radial runs its client on Node and,
   * if serve isn't answering, starts serve again rather than looking for a Mac
   * app (a checkout on a Mac has one). The Mac app leaves bin/radial to find
   * itself.
   */
  flavor?: 'headless';
}

function radialShimSource({ bin, sock, flavor }: ShimSourceOptions): string {
  if (!bin) throw new Error('radialShimSource: bin is required');
  const lines: string[] = [
    '#!/bin/sh',
    '# Radial CLI shim — generated by the app so `radial` is on PATH inside Radial terminals.',
    "# Points at the running app's bundle; regenerated on every launch.",
  ];
  if (sock) lines.push(`export RADIAL_CLI_SOCK="\${RADIAL_CLI_SOCK:-${dq(sock)}}"`);
  if (flavor) lines.push(`export RADIAL_CLI_FLAVOR="${dq(flavor)}"`);
  lines.push(`exec "${dq(bin)}" "$@"`);
  return lines.join('\n') + '\n';
}

export { radialShimSource };
